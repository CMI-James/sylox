#!/usr/bin/env node
// Regenerates content/docs/contract-reference.mdx from real source,
// never hand-written (brief: "Contract reference is generated, not
// hand-written"). Named contract-reference.mdx, NOT
// contract-reference.generated.mdx: Fumadocs derives this page's own
// URL slug from its filename (minus .mdx), and every other page here
// and meta.json's own nav order already link to /docs/contract-reference
// - a ".generated" suffix in the filename would leak into the URL
// itself. The file's own banner comment below (plus CI's drift check)
// already makes "generated, don't hand-edit" unmistakable without
// needing it in the route.
//
//   - Contract addresses: deployments/testnet.json (same file
//     packages/sdk/scripts/generate-networks.mjs reads).
//   - Functions and types: the generated bindings at
//     packages/sdk/src/contracts/{risk-oracle,event-registry}/src/
//     client.ts (the `Client` interface's own method signatures) and
//     types.ts (the `Error` map and every exported interface/union).
//   - Error codes: packages/sdk/src/errors.ts's own curated per-action
//     maps (FINALIZE_ERRORS, CHECKPOINT_CURE_ERRORS, SCORE_ERRORS,
//     COVER_GATE_ERRORS, PROPOSE_TIER1_ERRORS, CHALLENGE_ERRORS), each
//     entry `{name, message}` keyed by numeric code - the plain-English
//     copy a caller actually sees, not the raw contract doc comment.
//
// This is a deliberately lightweight, regex/line-based extractor, not
// a real TypeScript parser - the same "read real source, write a
// generated file" shape as generate-networks.mjs, just over .ts files
// instead of .json. A full AST parse (e.g. via the `typescript`
// package) would be more robust to a source shape change, but these
// bindings files are themselves GENERATED by stellar-js generate in a
// consistent, predictable layout (see each contract's own README.md),
// so a full parser would be meaningfully more code for low marginal
// benefit here; if that layout ever changes enough to break this
// script's assumptions, the drift check below (which diffs this
// script's output against the committed file) catches it immediately
// rather than silently producing a stale or wrong reference page.
//
// Run via `npm run generate:contract-reference -w web/docs`, or
// automatically as this package's own `predev`/`prebuild`/`pretest`
// npm lifecycle hooks (see package.json) - either way, run it again
// any time deployments/testnet.json, either contract's types.ts/
// client.ts, or packages/sdk/src/errors.ts changes, and commit the
// result. CI's own drift-check step (.github/workflows/ci.yml, the
// web/docs job) fails the build if this file is out of sync with its
// real sources, same convention as packages/sdk's own
// networks.generated.ts drift check.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
// web/docs/scripts/ -> repo root is two levels up.
const repoRoot = path.resolve(__dirname, "../../..");
const docsRoot = path.resolve(__dirname, "..");
const sdkRoot = path.join(repoRoot, "packages", "sdk");

// Thrown rather than `process.exit()`-ed directly, so the parsing
// logic below stays testable (scripts/generate-contract-reference.test.ts
// imports these functions and asserts on thrown errors against
// deliberately malformed fixture source) without a test needing to
// fork a child process just to observe a failure. The CLI entrypoint
// at the bottom of this file is the only place that turns this back
// into a non-zero exit.
function die(message) {
  throw new Error(`generate-contract-reference: ${message}`);
}

function readRequired(fullPath) {
  if (!existsSync(fullPath)) {
    die(`${fullPath} not found.`);
  }
  return readFileSync(fullPath, "utf8");
}

function loadDeployment() {
  const deploymentPath = path.join(repoRoot, "deployments", "testnet.json");
  const raw = readRequired(deploymentPath);
  let parsed;
  try {
    parsed = JSON.parse(raw);
  } catch (err) {
    die(`${deploymentPath} is not valid JSON: ${err instanceof Error ? err.message : String(err)}`);
  }
  return parsed;
}

/**
 * Strips a block or line doc comment immediately preceding `index` in
 * `source` (the stellar-js generate bindings convention: every
 * documented symbol gets a `/** ... *\/` right above it with no blank
 * line in between) and returns its text, with leading `*`/whitespace
 * stripped from each line. Returns "" when there is no such comment.
 */
function extractPrecedingDocComment(source, index) {
  const before = source.slice(0, index);
  // The comment body is matched as "any run of characters containing
  // no literal */" (not a bare [\s\S]*? lazy match), so this can never
  // swallow past the NEAREST preceding comment's own closing */ into
  // an earlier, unrelated comment two methods back - a real bug this
  // script hit in testing: a lazy [\s\S]*?\*\/\s*$ matched from the
  // FIRST /** anywhere in `before` through to the last */, capturing
  // an entire unrelated method (and its signature) as "doc text" for
  // whichever method genuinely had no comment of its own but happened
  // to sit right after one that did.
  const match = before.match(/\/\*\*((?:[^*]|\*(?!\/))*)\*\/\s*$/);
  if (!match) return "";
  return match[1]
    .split("\n")
    .map((line) => line.replace(/^\s*\*\s?/, "").trimEnd())
    .filter((line, i, arr) => !(i === 0 && line === "") && !(i === arr.length - 1 && line === ""))
    .join("\n")
    .trim();
}

/**
 * Parses the `export const Error = { <code> : { message: "<Name>" }, ... }`
 * block that every generated types.ts file has (see risk-oracle/src/
 * types.ts and event-registry/src/types.ts). Returns an array of
 * { code, name, doc } in the order declared.
 */
function parseErrorEnum(typesSource) {
  const blockMatch = typesSource.match(/export const Error = \{([\s\S]*?)\n\}/);
  if (!blockMatch) die("could not find \"export const Error = { ... }\" block in types.ts");
  const block = blockMatch[1];

  const entries = [];
  // Matches "<code> : { message: "<Name>" }" possibly preceded by its
  // own doc comment, one entry per declared numeric code.
  const entryPattern = /(\d+)\s*:\s*\{\s*message:\s*"([^"]+)"\s*\}/g;
  let match;
  while ((match = entryPattern.exec(block)) !== null) {
    const doc = extractPrecedingDocComment(block, match.index);
    entries.push({ code: Number(match[1]), name: match[2], doc });
  }
  if (entries.length === 0) die("found an Error block but parsed zero entries from it - check the regex against the real file shape");
  return entries;
}

/**
 * Parses every exported `interface`/`type` declaration in a types.ts
 * file (skipping the `Error` const and the `ContractEvent` summary
 * union, which is trivially derivable from the *Event interfaces
 * already listed) into { name, kind, doc, signature }.
 */
function parseExportedTypes(typesSource) {
  const results = [];
  // Matches "export interface Name {" or "export type Name =" (the
  // generated bindings sometimes prefix the latter with a stray
  // leading space - see the raw file - so the pattern tolerates
  // optional leading whitespace before `export`).
  const declPattern = /^[ \t]*export (interface|type) (\w+)/gm;
  let match;
  while ((match = declPattern.exec(typesSource)) !== null) {
    const [kind, name] = [match[1], match[2]];
    if (name === "ContractEvent") continue; // derivable from the *Event interfaces below.
    const doc = extractPrecedingDocComment(typesSource, match.index);
    results.push({ name, kind, doc });
  }
  return results;
}

/**
 * Parses the `export interface Client { ... }` method signatures from
 * a generated client.ts file into { name, doc, signature }, in
 * declared order. Each method is a single logical line (possibly with
 * an inline comment above it) ending in `;` at the interface's own
 * indent level (2 spaces, per the generated file's own formatting).
 */
function parseClientMethods(clientSource) {
  const ifaceMatch = clientSource.match(/export interface Client \{([\s\S]*?)\n\}/);
  if (!ifaceMatch) die("could not find \"export interface Client { ... }\" block in client.ts");
  const block = ifaceMatch[1];

  const results = [];
  // Matches a method signature line: "  name(args): ReturnType;" at
  // the interface's own 2-space indent - never a nested brace line
  // (those belong to inline object-literal argument types, which stay
  // part of the same signature capture via the non-greedy match up to
  // the terminating ");" convention `stellar-js generate` always uses).
  const methodPattern = /^ {2}(\w+)\(([\s\S]*?)\): (.+?);$/gm;
  let match;
  while ((match = methodPattern.exec(block)) !== null) {
    const [, name, args, returnType] = match;
    const doc = extractPrecedingDocComment(block, match.index);
    results.push({
      name,
      doc,
      signature: `${name}(${args.trim()}): ${returnType.trim()}`,
    });
  }
  if (results.length === 0) die("found a Client interface but parsed zero methods from it - check the regex against the real file shape");
  return results;
}

function mdxEscape(text) {
  // MDX parses {{ and < as JSX-ish syntax; escape just enough that
  // TypeScript signatures/doc comments containing generics or braces
  // never break the build. Code spans/fences (used for every
  // signature) already protect most of this, but doc-comment prose
  // can contain a bare `<T>` or similar.
  let escaped = text.replaceAll("{", "&#123;").replaceAll("}", "&#125;");
  // This repo's own em/en-dash ban (no-em-dash-guard.sh - see this
  // PR's description) applies to every file it writes, including a
  // GENERATED one: some real doc comments in packages/sdk's bindings
  // predate that convention and use an em dash. Normalizing here (not
  // hand-editing the source files, which are out of this PR's scope)
  // keeps this generated page compliant no matter what the real
  // source text contains, the same way the rest of this script treats
  // source text as data to transform, never to pass through unchecked.
  // An em dash is normally already surrounded by its own spaces in
  // real prose ("a thing, like this" written with one instead of a
  // comma), so a naive " - " substitution would double them up;
  // collapsing any whitespace already adjacent to the dash first,
  // then inserting exactly one space on each side, keeps the result
  // readable either way (with or without pre-existing spaces). An en
  // dash (used mid-word, e.g. a numeric range) gets a plain hyphen
  // with no added spacing. Built from charCodeAt-safe code points
  // (String.fromCharCode), not a literal character or a \u escape
  // written directly in this file's own source text, so this file
  // itself never contains an em/en dash glyph for the repo's
  // em-dash guard hook to flag - the whole point of this function.
  const EM_DASH = String.fromCharCode(8212);
  const EN_DASH = String.fromCharCode(8211);
  escaped = escaped.split(EM_DASH).join(" EM_DASH_PLACEHOLDER ");
  escaped = escaped.replace(/\s*EM_DASH_PLACEHOLDER\s*/g, " - ");
  escaped = escaped.split(EN_DASH).join(" EN_DASH_PLACEHOLDER ");
  escaped = escaped.replace(/\s*EN_DASH_PLACEHOLDER\s*/g, "-");
  return escaped;
}

function renderErrorTable(entries) {
  const rows = entries
    .map(({ code, name, doc }) => `| ${code} | \`${name}\` | ${mdxEscape(doc).replaceAll("\n", " ") || "-"} |`)
    .join("\n");
  return `| Code | Name | Notes |\n| --- | --- | --- |\n${rows}`;
}

function renderSdkErrorTable(entries) {
  const rows = entries
    .map(({ code, name, message }) => `| ${code} | \`${name || "-"}\` | ${mdxEscape(message)} |`)
    .join("\n");
  return `| Code | Contract error name | Message shown to a caller |\n| --- | --- | --- |\n${rows}`;
}

// #### (depth 4), one level below the "### Types"/"### Functions"
// subsection headers these sit under: a flat page with ~35 functions
// per contract, each at the SAME depth as its own "### Functions"
// parent, turned the sidebar TOC into a wall of same-weight entries
// with no visible grouping (Fumadocs' TOC extraction walks every
// heading depth with no default cutoff - see remark-heading.js).
// app/docs/[[...slug]]/page.tsx filters the TOC to max depth 3, so
// these individual entries never reach the sidebar at all; the real
// section structure (## RiskOracle, ### Functions, ### Types, ###
// Contract error codes) still does. The heading itself (and its own
// anchor link) is unaffected - this only changes what level it's
// written at, not whether it exists or is linkable.
function renderTypes(types) {
  return types
    .map(({ name, kind, doc }) => {
      const heading = `#### \`${name}\``;
      const kindLine = kind === "interface" ? "Struct." : "Union/type alias.";
      const docBlock = doc ? `\n\n${mdxEscape(doc)}` : "";
      return `${heading}\n\n${kindLine}${docBlock}`;
    })
    .join("\n\n");
}

function renderMethods(methods) {
  return methods
    .map(({ name, doc, signature }) => {
      const heading = `#### \`${name}\``;
      const docBlock = doc ? `\n\n${mdxEscape(doc)}` : "";
      return `${heading}\n\n\`\`\`ts\n${signature}\n\`\`\`${docBlock}`;
    })
    .join("\n\n");
}

/**
 * Parses one SDK error-copy map (e.g. `const FINALIZE_ERRORS: ErrorCopyMap = { ... }`)
 * out of packages/sdk/src/errors.ts into [{ code, name, message }].
 */
function parseSdkErrorMap(errorsSource, constName) {
  const mapMatch = errorsSource.match(new RegExp(`const ${constName}: ErrorCopyMap = \\{([\\s\\S]*?)\\n\\};`));
  if (!mapMatch) die(`could not find "const ${constName}: ErrorCopyMap = { ... }" in errors.ts`);
  const block = mapMatch[1];

  const entries = [];
  // errors.ts formats some entries inline ("2: { name: "...", message:
  // "..." },") and others (whichever ones prettier line-wraps for
  // length) across multiple lines with the same fields - \s* between
  // every token below (not a literal space) covers both shapes.
  const entryPattern = /(\d+):\s*\{\s*name:\s*"([^"]*)",\s*message:\s*"([^"]*)",?\s*\}/g;
  let match;
  while ((match = entryPattern.exec(block)) !== null) {
    entries.push({ code: Number(match[1]), name: match[2], message: match[3] });
  }
  if (entries.length === 0) die(`found ${constName} but parsed zero entries from it - check the regex against the real file shape`);
  return entries.sort((a, b) => a.code - b.code);
}

function buildContractSection({ title, contractId, typesSource, clientSource }) {
  const errorEntries = parseErrorEnum(typesSource);
  const types = parseExportedTypes(typesSource);
  const methods = parseClientMethods(clientSource);

  // No hand-specified {#slug} heading anchor: that rehype/remark
  // "custom heading id" syntax isn't part of plain MDX (Fumadocs'
  // default pipeline, per its own manual-installation guide, wires in
  // no plugin for it) - MDX's own parser instead tries to read
  // `{#risk-oracle}` as a bare JS expression and fails outright. The
  // auto-generated slug from the heading text itself (e.g. "RiskOracle"
  // -> #riskoracle) is enough for this page's own in-page anchor links.
  return `## ${title}

**Testnet contract address:** \`${contractId}\`

Sample/testnet deployment only. This address changes on every
redeploy. Always read it from this page (regenerated at build time
from \`deployments/testnet.json\`) rather than copying it into your own
code as a literal.

### Functions

${renderMethods(methods)}

### Types

${renderTypes(types)}

### Contract error codes

Raw \`#[contracterror]\` codes as returned by the contract itself (its
own doc-comment text, not the plain-English copy a caller sees. See
"SDK error messages" below for that).

${renderErrorTable(errorEntries)}
`;
}

function buildSdkErrorsSection(errorsSource) {
  const sections = [
    { constName: "FINALIZE_ERRORS", title: "`finalizeError` (EventRegistry.finalize)" },
    { constName: "CHECKPOINT_CURE_ERRORS", title: "`checkpointCureError` (EventRegistry.checkpoint_cure)" },
    { constName: "SCORE_ERRORS", title: "`scoreError` (RiskOracle.score)" },
    { constName: "COVER_GATE_ERRORS", title: "`coverGateError` (EventRegistry.cover_gate)" },
    { constName: "PROPOSE_TIER1_ERRORS", title: "`proposeTier1Error` (EventRegistry.propose_tier1)" },
    { constName: "CHALLENGE_ERRORS", title: "`challengeError` (EventRegistry.challenge)" },
  ];

  const body = sections
    .map(({ constName, title }) => {
      const entries = parseSdkErrorMap(errorsSource, constName);
      return `### ${title}\n\n${renderSdkErrorTable(entries)}`;
    })
    .join("\n\n");

  return `## SDK error messages

\`@sylox/sdk\` (\`packages/sdk/src/errors.ts\`) wraps each contract call
with a plain-English message, keyed by the same numeric code, in a
thrown \`SyloxError\`. These are the messages an app built on the SDK
actually shows, not the raw contract error name above.

${body}
`;
}

function main() {
  const deployment = loadDeployment();
  const riskOracleId = deployment?.contracts?.risk_oracle?.id;
  const eventRegistryId = deployment?.contracts?.event_registry?.id;
  if (!riskOracleId) die("deployments/testnet.json is missing contracts.risk_oracle.id");
  if (!eventRegistryId) die("deployments/testnet.json is missing contracts.event_registry.id");

  const riskOracleSection = buildContractSection({
    title: "RiskOracle",
    contractId: riskOracleId,
    typesSource: readRequired(path.join(sdkRoot, "src/contracts/risk-oracle/src/types.ts")),
    clientSource: readRequired(path.join(sdkRoot, "src/contracts/risk-oracle/src/client.ts")),
  });

  const eventRegistrySection = buildContractSection({
    title: "EventRegistry",
    contractId: eventRegistryId,
    typesSource: readRequired(path.join(sdkRoot, "src/contracts/event-registry/src/types.ts")),
    clientSource: readRequired(path.join(sdkRoot, "src/contracts/event-registry/src/client.ts")),
  });

  const sdkErrorsSection = buildSdkErrorsSection(readRequired(path.join(sdkRoot, "src/errors.ts")));

  const banner = `---
title: Contract reference
description: Contract addresses, functions, types, and error codes, generated from the deployed testnet contracts.
---

{/*
  GENERATED FILE - do not edit by hand.

  Produced by scripts/generate-contract-reference.mjs from:
    - deployments/testnet.json (contract addresses)
    - packages/sdk/src/contracts/(risk-oracle, event-registry)/src/(types, client).ts (functions, types, raw contract error codes)
    - packages/sdk/src/errors.ts (the plain-English SDK error messages)

  Regenerate with \`npm run generate:contract-reference -w web/docs\`
  (also runs automatically before dev/build/test via this package's
  own npm lifecycle hooks) any time one of those source files changes,
  then commit the result. CI's own drift-check step
  (.github/workflows/ci.yml, the web/docs job) fails the build if this
  file is out of sync with those sources, so it cannot silently drift
  against a real redeploy.

  MDX comments must use this slash-star form, not a plain HTML-style
  bang comment (MDX's own parser rejects that one outright, and even
  typing its exact syntax in prose here as plain text broke this very
  banner once already - MDX scans for tag-like tokens before it gets
  to parsing this block as JS). This also means the comment's own
  CONTENTS are parsed as a JS expression (it is still a JSX expression
  container) - this text deliberately avoids writing any bare curly
  braces too (e.g. a brace-expansion-style path list), the other thing
  that broke this same banner during development.
*/}

# Contract reference

Testnet only. Every address, function, type, and error code below is
read from the actual deployed testnet contracts and the SDK's own
source at generation time. Nothing on this page is hand-written.
`;

  const body = `${riskOracleSection}\n${eventRegistrySection}\n${sdkErrorsSection}`;

  const outPath = path.join(docsRoot, "content", "docs", "contract-reference.mdx");
  writeFileSync(outPath, `${banner}\n${body}`);
  console.log(`generate-contract-reference: wrote ${outPath}`);
}

// Only run as a CLI (`node scripts/generate-contract-reference.mjs`,
// or via the npm scripts that invoke it) - not when imported, which is
// exactly what scripts/generate-contract-reference.test.ts does to
// exercise the parsing/rendering functions directly against fixture
// source instead of this repo's own real files.
if (import.meta.url === `file://${process.argv[1]}`) {
  try {
    main();
  } catch (err) {
    console.error(err instanceof Error ? err.message : String(err));
    process.exit(1);
  }
}

